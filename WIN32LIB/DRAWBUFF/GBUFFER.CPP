extern void Unblock_Mouse(GraphicBufferClass *buffer);

BOOL GraphicBufferClass::Lock(void)
{
	/*
	**	All surfaces live in system memory, so locking always succeeds. The lock count is
	**	still maintained because a few routines look at it.
	*/
	LockCount++;
	TotalLocks++;
	return(TRUE);
}

/***************************************************************************
 * GBC::UNLOCK -- Unlocks a direct draw surface                            *
 *                                                                         *
 * INPUT:		none                                                        *
 *                                                                         *
 * OUTPUT:     none                                                        *
 *                                                                         *
 * HISTORY:                                                                *
 *   10/09/1995     : Created.                                             *
 *   10/09/1995     : Code stolen from Steve Tall                          *
 *=========================================================================*/


BOOL GraphicBufferClass::Unlock(void)
{
	if (LockCount > 0) {
		LockCount--;
	}

	/*
	**	Drawing into the visible page has finished -- let the platform layer know that the
	**	screen needs to be refreshed.
	*/
	if (IsVisible && LockCount == 0) {
		Video_Mark_Dirty();
	}
	return(TRUE);
}


